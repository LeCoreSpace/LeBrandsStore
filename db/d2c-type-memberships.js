export async function d2cTypeMembershipSeed() {
  const { payload: variants } = await d2cVariantSeed();
  const { payload: reviewed } = await reviewedCatalogueSeed();
  const known = new Set(variants.assignments.map(a => a.type_key));
  const overrides = new Map();
  for (const [ids, words] of GROUPS) for (const key of words.split(/\s+/)) {
    if (!known.has(key)) throw Error(`Unknown type membership override: ${key}`);
    if (overrides.has(key)) {
      // Multiple explicit contexts combine; they never erase earlier contexts.
      overrides.set(key, [...new Set([...overrides.get(key), ...ids])]);
    } else overrides.set(key, ids);
  }
  const links = new Map();
  const add = (type_key, subcategory_id, basis) => {
    if (!Number.isSafeInteger(subcategory_id) || subcategory_id < 1) throw Error("Invalid subcategory");
    links.set(`${type_key}:${subcategory_id}`, { type_key, subcategory_id, basis });
  };
  // Preserve every reviewed association even where the new functional placement
  // is narrower. Corrections to previously approved links are a separate review.
  for (const link of reviewed.type_links) add(link.type_key, link.subcategory_id, "previously_reviewed");
  const missing = variants.assignments.filter(a=>!(overrides.get(a.type_key)||FAMILY[a.profile_key])?.length);
  if (missing.length) throw Error(`No explicit functional membership: ${missing.map(a=>a.type_key).join(", ")}`);
  for (const a of variants.assignments) {
    const ids = overrides.get(a.type_key) || FAMILY[a.profile_key];
    if (!ids?.length) throw Error(`No explicit functional membership: ${a.type_key}`);
    for (const id of ids) if (!links.has(`${a.type_key}:${id}`))
      add(a.type_key, id, overrides.has(a.type_key) ? "curated_product_type" : `physical_family:${a.profile_key}`);
  }
  const assignments = [...links.values()].sort((a,b)=>a.type_key.localeCompare(b.type_key,"en")||a.subcategory_id-b.subcategory_id);
  if (new Set(assignments.map(a=>a.type_key)).size !== 1698) throw Error("Incomplete product-type coverage");
  const payload = { subcategories: NEW_SUBCATEGORIES, assignments };
  return { payload, sql: `INSERT INTO d2c_membership_seed(payload) VALUES ('${JSON.stringify(payload).replaceAll("'","''")}'::jsonb);` };
}
